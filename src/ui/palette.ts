/** A token's colour in an appearance; an unknown name is ink. */
export function paletteColor(scheme: "light" | "dark", token: string): string {
  const name = token in LIGHT ? (token as ColorToken) : "ink";
  return (scheme === "dark" ? DARK[name] : undefined) ?? LIGHT[name];
}

